import { createClient } from '@/lib/supabase/server'
import { NextRequest, NextResponse } from 'next/server'

export async function GET(request: NextRequest) {
  const { searchParams, origin } = request.nextUrl
  const code = searchParams.get('code')
  const next = searchParams.get('next') ?? '/'

  if (code) {
    const supabase = await createClient()
    const { error } = await supabase.auth.exchangeCodeForSession(code)
    if (!error) {
      return NextResponse.redirect(`${origin}${next}`)
    }
  }

  // Supabase email invitations return access and refresh tokens in the URL
  // hash, so the browser must finish the session setup on the client.
  return NextResponse.redirect(`${origin}/auth/accept-invite?next=${encodeURIComponent(next)}`)
}
